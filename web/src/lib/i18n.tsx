const zh = { ...baseZh, ...notesZh };
export type TextKey = keyof typeof zh;
const en: Record<TextKey, string> = { ...baseEn, ...notesEn };
export type Lang = "zh-CN" | "en";
const TABLES: Record<Lang, Record<TextKey, string>> = { "zh-CN": zh, en };

export function translator(lang: Lang) {
  return (key: TextKey, values: Record<string, string | number> = {}) =>
    (TABLES[lang][key] ?? zh[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

export const toLang = (code?: string): Lang => (String(code ?? "").toLowerCase().startsWith("en") ? "en" : "zh-CN");

export const I18n = createContext({ lang: "zh-CN" as Lang, t: translator("zh-CN") });
export const useI18n = () => useContext(I18n);
